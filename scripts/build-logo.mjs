// One-off: converts the brand Illustrator SVG exports into compact path data
// (components/brand/logo-paths.ts) and standalone SVG files (public/brand).
// Usage: node scripts/build-logo.mjs "<folder containing the brand SVGs>"
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { svgPathBbox } from "svg-path-bbox";

const dir = process.argv[2];
if (!dir) throw new Error("Pass the folder that holds the brand SVG exports");

const sources = {
  mark: { file: "Logo - Upedge - Final - Curved file-02.svg", take: 2 }, // U + chevron only
  wordmark: { file: "Logo - Upedge - Final - Curved file-09.svg" },
  full: { file: "Logo - Upedge - Final - Curved file-03.svg" }, // wordmark + tagline
};

const out = {};
for (const [key, { file, take }] of Object.entries(sources)) {
  const svg = readFileSync(join(dir, file), "utf8");
  let paths = [...svg.matchAll(/<path\s+([^>]*?)\/>/gs)].map((m) => {
    const d = /d="([^"]+)"/s.exec(m[1])[1].replace(/\s+/g, " ").trim();
    const accent = /class="st0"|class="st3"/.test(m[1]);
    return { d, accent };
  });
  if (take) paths = paths.slice(0, take);
  let [x0, y0, x1, y1] = [Infinity, Infinity, -Infinity, -Infinity];
  for (const { d } of paths) {
    const [a, b, c, e] = svgPathBbox(d);
    x0 = Math.min(x0, a); y0 = Math.min(y0, b); x1 = Math.max(x1, c); y1 = Math.max(y1, e);
  }
  const r = (n) => Math.round(n * 100) / 100;
  out[key] = { viewBox: `${r(x0)} ${r(y0)} ${r(x1 - x0)} ${r(y1 - y0)}`, width: r(x1 - x0), height: r(y1 - y0), paths };
}

writeFileSync(
  "components/brand/logo-paths.ts",
  `// Generated by scripts/build-logo.mjs from the brand SVG exports. Do not edit by hand.\n` +
    `export type LogoShape = { viewBox: string; width: number; height: number; paths: { d: string; accent: boolean }[] };\n` +
    `export const LOGO: Record<"mark" | "wordmark" | "full", LogoShape> = ${JSON.stringify(out, null, 1)};\n`
);

const file = (shape, ink, accent) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${shape.viewBox}">${shape.paths
    .map((p) => `<path fill="${p.accent ? accent : ink}" d="${p.d}"/>`)
    .join("")}</svg>`;
writeFileSync("public/brand/upedge-wordmark.svg", file(out.wordmark, "#0B0B0B", "#F99F1C"));
writeFileSync("public/brand/upedge-wordmark-light.svg", file(out.wordmark, "#FFFFFF", "#F99F1C"));
writeFileSync("public/brand/upedge-full.svg", file(out.full, "#0B0B0B", "#F99F1C"));
writeFileSync("public/brand/upedge-mark.svg", file(out.mark, "#0B0B0B", "#F99F1C"));
// App icon: the minimal U monogram (ink U + accent chevron) on a white tile, so it reads in dark browser tabs.
{
  const [x, y, w, h] = out.mark.viewBox.split(' ').map(Number);
  const pad = Math.max(w, h) * 0.2;
  const size = Math.max(w, h) + pad * 2;
  const vx = x - (size - w) / 2, vy = y - (size - h) / 2;
  const paths = out.mark.paths.map((p) => '<path fill="' + (p.accent ? '#F99F1C' : '#0D0D0D') + '" d="' + p.d + '"/>').join('');
  writeFileSync('app/icon.svg', '<svg xmlns="http://www.w3.org/2000/svg" viewBox="' + [vx, vy, size, size].map((n) => Math.round(n * 100) / 100).join(' ') + '"><rect x="' + vx + '" y="' + vy + '" width="' + size + '" height="' + size + '" rx="' + size * 0.22 + '" fill="#FFFFFF"/>' + paths + '</svg>');
}
console.log(Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.viewBox + " paths:" + v.paths.length])));
